# Writes src/courseBook.ts from descriptions.json + new-2627.json (both made by build.py).
#   cd scripts/coursebook && python3 build.py && python3 gen_ts.py
# catalog.json is the app's COURSES / ACADEMIES / EXTRAS at the time of the build;
# cb2526.txt / cb2627.txt are the text of the two Sentinel course books:
#   https://westvancouverschools.ca/ecole-sentinel-secondary/wp-content/uploads/sites/8/2025/01/2025-2026-Course-Book-Final.pdf
#   https://westvancouverschools.ca/ecole-sentinel-secondary/wp-content/uploads/sites/8/2026/05/2026-2027-Course-Handbook_Updated-Fees-May-21_2026.pdf
import json, os

here = os.path.dirname(os.path.abspath(__file__))
d = json.load(open(os.path.join(here, 'descriptions.json')))
new = json.load(open(os.path.join(here, 'new-2627.json')))
book = {}
for name, e in {**d['courses'], **new}.items():
    if not e or not e.get('desc'):
        continue
    out = {'desc': e['desc'].strip()}
    if e.get('prereq'):
        out['prereq'] = e['prereq'].strip()
    book[name] = out

lines = [
    '// Generated by scripts/coursebook/gen_ts.py from the Sentinel course books',
    '// (2026-27 handbook first, 2025-26 book for courses it dropped; academies from',
    '// westvancouverschools.ca/academies). Text is word for word. Do not hand-edit: regenerate.',
    '',
    'export const COURSE_BOOK: Record<string, { desc: string; prereq?: string }> = {',
]
for k in sorted(book):
    lines.append(f'  {json.dumps(k, ensure_ascii=False)}: {json.dumps(book[k], ensure_ascii=False)},')
lines.append('};')
open(os.path.join(here, '..', '..', 'src', 'courseBook.ts'), 'w').write('\n'.join(lines) + '\n')
print(len(book), 'entries')
