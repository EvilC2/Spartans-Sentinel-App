// Emits supabase/seed/badges.sql from src/badges.ts (parsed as text — the
// module needs Metro's require() for badge art). RARITY_XP copied from src/xp.ts.
//   node scripts/badge-seed.mjs > supabase/seed/badges.sql
import { readFileSync } from 'node:fs';
const src = readFileSync(new URL('../src/badges.ts', import.meta.url), 'utf8');
const RARITY_XP = { common: 10, uncommon: 25, rare: 50, epic: 100, legendary: 200, exotic: 400, special: 75, seasonal: 40, secret: 150 };
const slug = s => s.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const rowsSrc = src.slice(src.indexOf('const ROWS'), src.indexOf('export const BADGES'));
const STR = `(?:'((?:[^'\\\\]|\\\\.)*)'|"((?:[^"\\\\]|\\\\.)*)")`;   // one JS string literal, either quote
const rows = [...rowsSrc.matchAll(new RegExp(`^\\s*\\[${STR},\\s*${STR},\\s*'(\\w+)'`, 'gm'))]
  .map(([, t1, t2, , , rarity]) => ({ title: (t1 ?? t2).replace(/\\(['"])/g, '$1'), rarity }));
if (!rows.length || rows.some(r => !(r.rarity in RARITY_XP))) throw new Error('parse failed');
const q = s => `'${String(s).replace(/'/g, "''")}'`;
console.log(`-- GENERATED by scripts/badge-seed.mjs from src/badges.ts. Regenerate, don't hand-edit.
insert into badge_catalog (id, title, rarity, xp) values
${rows.map(b => `  (${q(slug(b.title) || 'unknown')}, ${q(b.title)}, ${q(b.rarity)}, ${RARITY_XP[b.rarity]})`).join(',\n')}
on conflict (id) do update set title = excluded.title, rarity = excluded.rarity, xp = excluded.xp;`);
