const BY_KIND: Record<ProgramKind, SubjectArt> = {
  class: 'books', outside: 'books', online: 'laptop', sport: 'trophy', music: 'notes', extra: 'sparkles', club: 'star',
};

export const subjectArt = (name: string, kind: ProgramKind = 'class'): SubjectArt => {
  for (const [re, art] of RULES) if (re.test(name)) return art;
  return BY_KIND[kind];
};

export const subjectImage = (name: string, kind?: ProgramKind): ImageSourcePropType => ART[subjectArt(name, kind)];
